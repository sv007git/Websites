import { Project } from '@webforge/schema';
import { GeneratedFile } from '../nextjs/nextjs-generator';

export function generateStaticHtmlProject(project: Project): GeneratedFile[] {
  const files: GeneratedFile[] = [];

  project.pages.forEach((page) => {
    const fileName = page.isHome || page.slug === '/' ? 'index.html' : `${page.slug.replace(/^\//, '')}.html`;
    files.push({
      path: fileName,
      content: `<!DOCTYPE html>
<html lang="en" class="dark">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>${page.seo.title || page.name} | ${project.name}</title>
    <meta name="description" content="${page.seo.description || project.description}">
    <script src="https://cdn.tailwindcss.com"></script>
    <style>
        :root {
            --primary: ${project.theme.colors.primary};
            --background: ${project.theme.colors.background};
            --text: ${project.theme.colors.text};
        }
    </style>
</head>
<body class="bg-slate-950 text-slate-100 min-h-screen flex flex-col font-sans">
    <header class="bg-slate-900 border-b border-slate-800 py-4 px-6">
        <div class="max-w-7xl mx-auto flex items-center justify-between">
            <span class="font-bold text-lg text-white">${project.name}</span>
            <nav class="flex items-center gap-6 text-sm text-slate-300">
                ${project.pages
                  .map(
                    (p) =>
                      `<a href="${p.isHome || p.slug === '/' ? 'index.html' : p.slug.replace(/^\//, '') + '.html'}" class="hover:text-white">${p.name}</a>`
                  )
                  .join('\n                ')}
            </nav>
        </div>
    </header>

    <main class="flex-1 max-w-7xl mx-auto px-4 py-12 w-full space-y-12">
        <div class="space-y-4">
            <h1 class="text-4xl font-extrabold text-white">${page.name}</h1>
            <p class="text-slate-400">${page.seo.description || project.description}</p>
        </div>

        <div class="space-y-8">
            ${page.blocks
              .filter((b) => !b.hidden)
              .map(
                (b) => `
            <section id="${b.id}" class="p-8 rounded-2xl bg-slate-900 border border-slate-800 space-y-2">
                <span class="text-xs uppercase font-mono text-blue-400 font-bold">${b.type}</span>
                ${b.props.title ? `<h3 class="text-2xl font-bold text-white">${b.props.title}</h3>` : ''}
                ${b.props.subtitle ? `<p class="text-xs text-slate-400">${b.props.subtitle}</p>` : ''}
                ${b.props.description ? `<p class="text-xs text-slate-400">${b.props.description}</p>` : ''}
            </section>`
              )
              .join('\n            ')}
        </div>
    </main>

    <footer class="py-6 bg-slate-950 border-t border-slate-900 text-center text-xs text-slate-500">
        <p>&copy; ${new Date().getFullYear()} ${project.name}. Static HTML export by WebForge Studio.</p>
    </footer>
</body>
</html>
`,
    });
  });

  files.push({
    path: 'README.md',
    content: `# ${project.name} (Static HTML/CSS Export)

Generated by **WebForge Studio**. This is a purely static bundle ready to deploy on GitHub Pages, Netlify, Cloudflare Pages, or AWS S3.

Open \`index.html\` directly in your browser.
`,
  });

  return files;
}
